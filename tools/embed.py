import sys
from pathlib import Path

src, dst = map(Path, sys.argv[1:3])
data = src.read_bytes()

with dst.open("w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by tools/embed.py - do not edit.\n")
    f.write("#pragma once\n#include <cstddef>\n\n")
    f.write("alignas(16) static const unsigned char kEmbeddedDll[] = {\n")
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        f.write(f"    {chunk},\n")
    f.write("};\n")
    f.write(f"static const size_t kEmbeddedDllSize = {len(data)};\n")

print(f"embedded {len(data)} bytes -> {dst}")
